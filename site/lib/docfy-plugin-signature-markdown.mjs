import { readFileSync } from 'fs';

const SIGNATURE_TAG_PATTERN = /<Signature\s+([^>]*?)\/>/g;
const ATTR_PATTERN = /@(component|package|module)="([^"]*)"/g;

// Matches the exact template site/lib/generate-signature-data.js writes to
// signature-data.ts: `const data: ComponentDoc[] = [...];\nexport type ...`.
// That script runs the file through Prettier afterward, which reformats the
// array into single-quoted JS object-literal syntax - valid JS, but no
// longer valid JSON - so it can't be JSON.parse'd, only evaluated as JS.
const DATA_ARRAY_PATTERN =
  /const data: ComponentDoc\[\] = (\[[\s\S]*\]);\nexport type/;

// Both producers of this data — lowlight for types, remark for descriptions —
// emit HTML, so `<` and `&` arrive escaped. Dropping the tags without decoding
// the entities leaves things like `SlotsToClasses&#x3C;'base'>` in the markdown.
const ENTITIES = {
  '&#x3C;': '<',
  '&#x3E;': '>',
  '&lt;': '<',
  '&gt;': '>',
  '&quot;': '"',
  '&#39;': "'",
  '&#x27;': "'",
  '&nbsp;': ' ',
};

function decodeEntities(value) {
  return (
    value
      .replace(
        /&(?:#x3C|#x3E|lt|gt|quot|#39|#x27|nbsp);/gi,
        (match) => ENTITIES[match.toLowerCase()] ?? ENTITIES[match] ?? match,
      )
      // `&amp;` last, so a double-escaped `&amp;lt;` doesn't become a tag.
      .replace(/&amp;/g, '&')
  );
}

function stripHtml(value) {
  return typeof value === 'string'
    ? decodeEntities(value.replace(/<[^>]*>/g, ''))
    : value;
}

// The mirror image of generate-signature-data.js's highlight() step: that
// script bakes hljs-* syntax-highlighting spans into type/defaultValue
// strings for the browser-rendered Signature component. This plugin only
// wants the plain text, so it strips them back out at read time rather than
// requiring a second, separately-generated plain-data file to stay in sync.
function stripHighlighting(property) {
  // `type.items` (union members) are plain strings in the generated data,
  // never HTML-highlighted in the first place - nothing to strip.
  if (!property || typeof property !== 'object') {
    return;
  }

  if (property.type) {
    property.type.type = stripHtml(property.type.type);

    if (property.type.raw) {
      property.type.raw = stripHtml(property.type.raw);
    }

    if (property.type.items && property.type.items.length > 0) {
      property.type.items.forEach(stripHighlighting);
    }
  }

  if (property.defaultValue) {
    property.defaultValue = stripHtml(property.defaultValue);
  }
}

export function loadSignatureData(signatureDataTsPath) {
  const source = readFileSync(signatureDataTsPath, 'utf-8');
  const match = source.match(DATA_ARRAY_PATTERN);

  if (!match) {
    throw new Error(
      `[docfy-plugin-signature-markdown] Could not find the generated data array in ${signatureDataTsPath} — has site/lib/generate-signature-data.js's output format changed?`,
    );
  }

  // The array is JS (single-quoted, may have trailing commas), not strict
  // JSON, since Prettier reformats it - so it's evaluated as a JS expression
  // rather than JSON.parse'd. Safe here: this file is generated by our own
  // site/lib/generate-signature-data.js from our own source, never from
  // untrusted input.
  // eslint-disable-next-line no-new-func
  const components = new Function(`return (${match[1]});`)();

  components.forEach((component) => {
    (component.Args || []).forEach(stripHighlighting);
    (component.Blocks || []).forEach(stripHighlighting);
    stripHighlighting(component.Element);
  });

  return components;
}

export function parseSignatureTag(attrsString) {
  const tag = {};
  let match;

  ATTR_PATTERN.lastIndex = 0;
  while ((match = ATTR_PATTERN.exec(attrsString)) !== null) {
    tag[match[1]] = match[2];
  }

  return tag;
}

export function findComponent(signatureData, tag) {
  return signatureData.find((entry) => {
    return (
      entry.name === tag.component &&
      (!tag.package || entry.package === tag.package) &&
      (!tag.module || entry.module === tag.module)
    );
  });
}

function shouldIgnoreArg(tags) {
  return Boolean(tags && Object.keys(tags).includes('ignore'));
}

function escapeCell(text) {
  return String(text)
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ')
    .trim();
}

function formatType(type) {
  if (!type) {
    return '';
  }

  const value = type.raw || type.type;

  return value ? `\`${escapeCell(value)}\`` : '';
}

function formatDescription(item) {
  // Descriptions are stored as rendered HTML for the browser table, the same as
  // types are stored highlighted. Strip back to text for the markdown output.
  const description = item.description
    ? escapeCell(stripHtml(item.description))
    : '';

  return item.isInternal ? `${description} _(internal)_`.trim() : description;
}

function buildPropertiesTable(items) {
  const rows = (items || []).filter((item) => !shouldIgnoreArg(item.tags));

  if (rows.length === 0) {
    return '';
  }

  const lines = [
    '| Name | Type | Default | Description |',
    '| --- | --- | --- | --- |',
  ];

  rows.forEach((item) => {
    const name = item.isRequired ? `${item.identifier} *` : item.identifier;
    const type = formatType(item.type);
    const defaultValue = item.defaultValue
      ? `\`${escapeCell(item.defaultValue)}\``
      : '-';
    const description = formatDescription(item);

    lines.push(
      `| \`${escapeCell(name)}\` | ${type} | ${defaultValue} | ${description} |`,
    );
  });

  return lines.join('\n');
}

export function buildSignatureMarkdown(entry) {
  const lines = [`### ${entry.name}`, ''];

  if (entry.description) {
    // Stored as rendered HTML for the browser table; the markdown output wants
    // text. Paragraph breaks become blank lines so multi-paragraph component
    // descriptions don't collapse into one run-on line.
    lines.push(
      stripHtml(entry.description.replace(/<\/p>\s*<p>/g, '\n\n')),
      '',
    );
  }

  if (entry.Element && entry.Element.type && entry.Element.type.type) {
    lines.push(`**Element:** \`${entry.Element.type.type}\``, '');
  }

  lines.push('**Arguments**', '');
  lines.push(buildPropertiesTable(entry.Args) || '_No arguments._', '');

  if (entry.Blocks && entry.Blocks.length > 0) {
    const blocksTable = buildPropertiesTable(entry.Blocks);

    if (blocksTable) {
      lines.push('**Blocks**', '', blocksTable, '');
    }
  }

  return lines.join('\n').trimEnd();
}

function describeTag(tag) {
  const parts = [`@component="${tag.component}"`];

  if (tag.package) {
    parts.push(`@package="${tag.package}"`);
  }

  if (tag.module) {
    parts.push(`@module="${tag.module}"`);
  }

  return `<Signature ${parts.join(' ')} />`;
}

export function resolveSignatureTags(markdown, signatureData, pageUrl) {
  return markdown.replace(SIGNATURE_TAG_PATTERN, (match, attrsString) => {
    const tag = parseSignatureTag(attrsString);

    if (!tag.component) {
      return match;
    }

    const entry = findComponent(signatureData, tag);

    if (!entry) {
      console.warn(
        `[docfy-plugin-signature-markdown] No component found for ${describeTag(tag)} on page ${pageUrl}`,
      );

      return match;
    }

    return buildSignatureMarkdown(entry);
  });
}

export function docfyPluginSignatureMarkdown(signatureData) {
  return {
    runAfter(ctx) {
      ctx.pages.forEach((page) => {
        const resolved = resolveSignatureTags(
          page.markdown,
          signatureData,
          page.meta.url,
        );

        if (resolved !== page.markdown) {
          page.pluginData.staticMarkdown = resolved;
        }
      });
    },
  };
}

export default docfyPluginSignatureMarkdown;
